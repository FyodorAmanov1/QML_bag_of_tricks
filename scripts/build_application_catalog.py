"""Validate published application leads and render their documentation index.

This consumes literature records, not benchmark outputs. It never trains a model
or changes an evidence status. New local reproductions belong in their own reports.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs/use_cases/catalog.json"
INDEX = ROOT / "docs/use_cases/index.md"


def validate_catalog(catalog: dict, directory: Path) -> None:
    """Reject ambiguous units, missing comparators and promoted evidence labels."""
    if catalog.get("schema_version") != 1 or not catalog.get("checked_on"):
        raise ValueError("Expected schema_version 1 and a source-check date")
    applications = catalog.get("applications", [])
    if not applications:
        raise ValueError("No applications supplied")
    seen = set()
    for app in applications:
        name = app["id"]
        if name in seen:
            raise ValueError(f"Duplicate application: {name}")
        seen.add(name)
        if app.get("status") != "paper_reported_not_locally_reproduced":
            raise ValueError(f"{name}: a literature record cannot become a local reproduction")
        publication = app["publication"]
        if publication.get("peer_reviewed") is not True:
            raise ValueError(f"{name}: peer-reviewed publication required")
        for field in ("doi", "venue", "year", "locator", "url", "primary_result_url"):
            if not publication.get(field):
                raise ValueError(f"{name}: missing publication {field}")
        for field in ("experimental_scope", "headline_caveat", "uncertainty", "acceptance_checks"):
            if not app.get(field):
                raise ValueError(f"{name}: missing {field}")
        guide = (directory / app["guide"]).resolve()
        if not guide.is_relative_to(directory.resolve()) or not guide.is_file():
            raise ValueError(f"{name}: guide must exist inside the catalog directory")
        metric = app["metric"]
        if (metric.get("unit"), metric.get("direction")) not in {
            ("fraction", "higher"), ("fraction", "lower"), ("epochs", "lower")
        }:
            raise ValueError(f"{name}: unsupported metric unit/direction")
        baselines = app.get("classical_comparators", [])
        if not baselines:
            raise ValueError(f"{name}: a named classical comparator is required")
        kind = app.get("comparison_kind", "numeric")
        if kind not in {"numeric", "qualitative_figure"}:
            raise ValueError(f"{name}: unknown comparison kind")
        if kind == "qualitative_figure" and not app.get("comparison_summary"):
            raise ValueError(f"{name}: a figure comparison needs a sourced summary")
        models = [app["quantum"], *baselines]
        for model in models:
            value = model.get("value")
            if kind == "qualitative_figure":
                if not model.get("model") or value is not None:
                    raise ValueError(f"{name}: figure-only comparisons must not invent numeric scores")
                continue
            if not model.get("model") or isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError(f"{name}: invalid model or score")
            if metric["unit"] == "fraction" and not 0 <= value <= 1:
                raise ValueError(f"{name}: fractional score outside [0, 1]")
            if metric["unit"] == "epochs" and value <= 0:
                raise ValueError(f"{name}: epochs must be positive")
        if app["backend"] not in {"noiseless_gate_simulator", "quantum_annealer"}:
            raise ValueError(f"{name}: specify a supported execution setting")
        upstream = app["upstream"]
        if not upstream.get("code_access") or not upstream.get("data_access"):
            raise ValueError(f"{name}: code and data readiness must be explicit")
        if app["implementation"] == "implementation_guide_and_upstream_code" and not upstream.get("code_url"):
            raise ValueError(f"{name}: claimed upstream code has no URL")
        if app["implementation"] == "runnable_reference_adaptation":
            local = app.get("local_model", {})
            if not local.get("class") or local.get("case") not in {"entity_matching", "multiclass_kernel", "adversarial_qvc"}:
                raise ValueError(f"{name}: runnable adaptation needs a named local model and case")


def format_score(value: float, metric: dict) -> str:
    if metric["unit"] == "epochs":
        return f"{value:,.0f} epochs"
    if metric["name"] == "test accuracy":
        return f"{100 * value:.1f}%"
    return f"{value:.4f} {metric['name']}"


def render(catalog: dict) -> str:
    runnable = [a for a in catalog["applications"] if a.get("local_model")]
    lines = [
        "<!-- Generated by scripts/build_application_catalog.py; edit catalog.json and case guides. -->",
        "# More published QML applications to explore", "",
        "These peer-reviewed studies report benefits on classical application inputs.",
        f"**{len(catalog['applications'])} paper cases; {len(runnable)} include runnable reduced model adaptations.**",
        "The published comparisons below are **not locally reproduced**. Local adaptation",
        "runs exercise the software and have their own outcomes; they do not establish the paper gains.", "",
        "For runnable local paper reproductions, start with [alloy prediction and wireless",
        "equalization](../reproductions/index.md). Their stronger classical follow-up controls",
        "remain in the [full results](../reproductions/results.md).", "",
        "## Reported comparisons", "",
        "Numerical rows use the best listed classical score for that recorded setting.",
        "Figure-only findings retain a qualitative comparison; no missing scores are invented.", "",
        "| Application | Reported quantum model | Classical comparator(s) | Scope to retain |",
        "|---|---|---|---|",
    ]
    for app in catalog["applications"]:
        metric = app["metric"]
        choose = max if metric["direction"] == "higher" else min
        q = app["quantum"]
        if app.get("comparison_kind") == "qualitative_figure":
            classical = ", ".join(item["model"] for item in app["classical_comparators"])
            lines.append(f"| [{app['title']}]({app['guide']}) | {q['model']}: {app['comparison_summary']} | {classical} | {app['headline_caveat']} |")
            continue
        baseline = choose(app["classical_comparators"], key=lambda item: item["value"])
        lines.append(
            f"| [{app['title']}]({app['guide']}) | {q['model']}: **{format_score(q['value'], metric)}** "
            f"| {baseline['model']}: {format_score(baseline['value'], metric)} | {app['headline_caveat']} |"
        )
    lines.extend([
        "", "A reported numerical difference alone does not establish statistical significance,",
        "a hardware speedup or superiority over every well-tuned classical model. Epoch savings",
        "and predictive accuracy are different benefits. The guides preserve that distinction.", "",
        "## Choose an implementation path", "",
        "| Project need | Suggested first experiment | Required control |",
        "|---|---|---|",
        "| Few labeled satellite images | A compressed classical encoder with a small quantum image head | The same encoder and auxiliary objective with a classical head |",
        "| A small imbalanced molecular endpoint | Binary selection of a fixed pool of weak learners | The identical selection problem solved classically |",
        "| Expensive neural-network tuning | Predict learning curves and stop unpromising trials | Classical prediction and an equally sized predictor ensemble |",
        "| Ambiguous record pairs | TF-IDF triage with a jointly trained hybrid quantum head | TF-IDF and a classical head on the same representation and route |",
        "| Multiclass tabular labels | Select a fidelity-kernel family using training/validation data | Tuned classical kernels and the exact classical product-kernel equivalent |",
        "| Transferred adversarial image perturbations | Amplitude-encoded QVC and a cross-model attack matrix | Independent classical targets, quantum white-box attacks and stronger attack sweeps |",
        "", "The molecular and hyperparameter-search studies use **quantum annealing**.",
        "Annealing requires its own solver interface. Existing Qiskit, PennyLane and Cirq",
        "recipes are building blocks for gate-model projects; substituting one for an",
        "annealer changes the method and requires a separate benchmark.", "",
        "Each guide contains a concrete agent task, split rules, classical controls, resource",
        "accounting and acceptance criteria. Its implementation plan is our recommendation,",
        "separate from the cited paper's experimental protocol.", "",
        "## Run the three new model adaptations", "",
        "Install `.[learning]` and the selected SDK, then run from a source checkout:", "",
        "```bash",
        "python -m qml_tricks.learning.case_models --case entity_matching --framework qiskit --output results/local/entity.json",
        "python -m qml_tricks.learning.case_models --case multiclass_kernel --framework pennylane --output results/local/multiclass.json",
        "python -m qml_tricks.learning.case_models --case adversarial_qvc --framework cirq --output results/local/robustness.json",
        "```", "",
        "All three cases support all three SDKs. [Model and benchmark instructions](models.md)",
        "explain custom data and the saved [nine-run reference report](../source/results/case_models_reference.json).",
        "The references use exact simulator states, small new splits and short training.",
        "They retain classical wins and do not assert that QML must outperform a control.", "",
        "## Evidence records and maintenance", "",
        f"Source links checked: **{catalog['checked_on']}**. The downloadable [catalog](catalog.json)",
        "stores DOI, result locator, units, every recorded comparator, execution setting,",
        "code/data readiness and the explicit evidence status. Linked upstream repositories were",
        "inspected for availability; their training pipelines were not executed here.", "",
        "From a source checkout, validate and regenerate this page with:", "",
        "```bash", "python scripts/build_application_catalog.py --check",
        "python scripts/build_application_catalog.py", "```", "",
        "A new reproduction needs saved predictions, split manifests, resource logs and an",
        "independent result audit. Add its measured report alongside these literature records;",
        "changing a status label does not create a reproduction.", "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate records and reject a stale index")
    args = parser.parse_args()
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    validate_catalog(catalog, CATALOG.parent)
    markdown = render(catalog)
    if args.check:
        if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != markdown:
            raise SystemExit("Application index is stale; run scripts/build_application_catalog.py")
        print(f"Validated {len(catalog['applications'])} published application records and their index")
    else:
        INDEX.write_text(markdown, encoding="utf-8", newline="\n")
        print(f"Wrote {INDEX.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

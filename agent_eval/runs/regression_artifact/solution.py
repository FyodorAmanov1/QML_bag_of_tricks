"""Reproduce a bounded synthetic regression and trusted local model round trip."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np
from sklearn.linear_model import Ridge
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from qml_tricks.learning.models import QMLModel


def main():
    output = Path(__file__).resolve().parent
    seed = 31
    rng = np.random.default_rng(seed)
    x = rng.normal(size=(80, 3))
    y = (1.2 * x[:, 0] - 0.7 * x[:, 1] + 0.5 * np.sin(x[:, 2])
         + rng.normal(scale=0.08, size=len(x)))
    train, test = train_test_split(np.arange(len(x)), test_size=0.25,
                                   random_state=seed)
    assert not set(train).intersection(test)
    quantum = QMLModel(method="frozen_features", task="regression",
                       framework="qiskit", n_qubits=3, depth=1,
                       seed=seed, shots=None, steps=0, regularization=0.1)
    quantum.fit(x[train], y[train])
    baseline = make_pipeline(StandardScaler(), Ridge(alpha=0.1))
    baseline.fit(x[train], y[train])

    # Save before any test predictions so reload verification acquires fresh
    # features rather than simply recovering cached test features.
    artifact = output / "frozen_features.joblib"
    quantum.save(artifact)
    restored = QMLModel.load(artifact)
    predicted = quantum.predict(x[test])
    reloaded_prediction = restored.predict(x[test])
    classical_prediction = baseline.predict(x[test])
    reload_error = float(np.max(np.abs(predicted - reloaded_prediction)))
    assert np.array_equal(predicted, reloaded_prediction)
    actual_mean = x[train].mean(axis=0)
    np.testing.assert_allclose(quantum.scaler_.mean_, actual_mean, rtol=0, atol=0)
    np.testing.assert_allclose(baseline[0].mean_, actual_mean, rtol=0, atol=0)
    rmse = lambda values: float(np.sqrt(np.mean((values - y[test]) ** 2)))
    scores = {"frozen_features": rmse(predicted),
              "classical_ridge": rmse(classical_prediction)}
    report = {
        "task": "regression", "seed": seed, "n_examples": len(x),
        "rmse": scores,
        "frozen_features_rmse": scores["frozen_features"],
        "classical_ridge_rmse": scores["classical_ridge"],
        "train_indices": train.tolist(), "test_indices": test.tolist(),
        "reload_max_error": reload_error,
        "preprocessing_train_mean": quantum.scaler_.mean_.tolist(),
        "actual_train_mean": actual_mean.tolist(),
        "classical_preprocessing_train_mean": baseline[0].mean_.tolist(),
        "test_targets": y[test].tolist(),
        "test_predictions": {"frozen_features": predicted.tolist(),
                             "classical_ridge": classical_prediction.tolist(),
                             "reloaded": reloaded_prediction.tolist()},
        "artifact": str(artifact.relative_to(ROOT)),
        "resources": quantum.resources_,
        "reloaded_resources": restored.resources_,
        "configuration": {"framework": "qiskit", "n_qubits": 3,
                          "depth": 1, "shots": None,
                          "regularization": 0.1, "steps": 0},
        "limitations": [
            "Synthetic IID rows; fixed settings and no hyperparameter selection.",
            "Scaling and PCA are fit only on training rows. The classical ridge uses the same rows and raw standardized features.",
            "Frozen angles; only the classical ridge readout is fitted. No claim of useful general features or quantum advantage.",
            "Classical numeric input loading; each uncached row requires native simulator execution and exact local Z readout. No hardware shots or QPU jobs.",
            "Classical full-state simulation uses 16*2**3=128 statevector bytes, excluding SDK/workspace overhead; feature cache and ridge head also use classical memory.",
            "Joblib round-trip uses only the trusted model generated by this script."
        ]
    }
    (output / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    np.savetxt(output / "data.csv", np.column_stack([x, y]), delimiter=",",
               header="x0,x1,x2,target", comments="")
    print(json.dumps({"rmse": scores, "reload_max_error": reload_error,
                      "train_rows": len(train), "test_rows": len(test)}))


if __name__ == "__main__":
    main()
